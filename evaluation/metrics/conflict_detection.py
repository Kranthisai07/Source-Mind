"""Metric 3: Conflict Detection — measures the system's ability to flag
contradictory knowledge pairs.

Requires a dataset of (item_a, item_b, is_conflict) pairs. The metric
computes precision, recall, and F1 for conflict detection.

For evaluation, synthetic conflict pairs are generated by pairing items
with opposing states (e.g., open vs. closed issues on the same topic).
"""

from __future__ import annotations

from typing import Any


def _cosine_sim(a: list[float], b: list[float]) -> float:
    """Cosine similarity between two vectors."""
    dot = sum(x * y for x, y in zip(a, b))
    norm_a = sum(x * x for x in a) ** 0.5
    norm_b = sum(x * x for x in b) ** 0.5
    if norm_a == 0 or norm_b == 0:
        return 0.0
    return dot / (norm_a * norm_b)


def conflict_detection_f1(
    predictions: list[bool],
    ground_truth: list[bool],
) -> dict[str, Any]:
    """Compute precision, recall, and F1 for conflict detection.

    Args:
        predictions: List of booleans — True if system flagged a conflict.
        ground_truth: List of booleans — True if the pair is a real conflict.

    Returns:
        Dict with ``precision``, ``recall``, ``f1``, ``tp``, ``fp``, ``fn``.
    """
    if len(predictions) != len(ground_truth):
        raise ValueError("predictions and ground_truth must be the same length")

    tp = sum(1 for p, g in zip(predictions, ground_truth) if p and g)
    fp = sum(1 for p, g in zip(predictions, ground_truth) if p and not g)
    fn = sum(1 for p, g in zip(predictions, ground_truth) if not p and g)

    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = (
        2 * precision * recall / (precision + recall)
        if (precision + recall) > 0
        else 0.0
    )

    return {
        "metric": "conflict_detection",
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1": round(f1, 4),
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "total": len(predictions),
    }


def build_conflict_pairs(
    dataset: list[dict[str, Any]],
) -> list[tuple[dict[str, Any], dict[str, Any], bool]]:
    """Generate synthetic conflict pairs for evaluation.

    Two items from the same repo with opposite issue states (open vs. closed)
    on the same topic are labelled as conflicts. All other cross-repo pairs
    are non-conflicts.

    Args:
        dataset: Ground-truth items.

    Returns:
        List of ``(item_a, item_b, is_conflict)`` tuples.
    """
    pairs: list[tuple[dict[str, Any], dict[str, Any], bool]] = []
    issues = [i for i in dataset if i.get("artifact_type") == "issue"]

    # Group by repo
    by_repo: dict[str, list[dict[str, Any]]] = {}
    for issue in issues:
        repo = issue.get("repo", "")
        by_repo.setdefault(repo, []).append(issue)

    for repo_issues in by_repo.values():
        open_issues = [i for i in repo_issues if (i.get("metadata") or {}).get("state") == "open"]
        closed_issues = [i for i in repo_issues if (i.get("metadata") or {}).get("state") == "closed"]
        # Pair open vs. closed issues from same repo as synthetic "conflicts"
        for a in open_issues[:5]:
            for b in closed_issues[:5]:
                if a["id"] != b["id"]:
                    pairs.append((a, b, True))

    return pairs
