"""Generate ``Dockerfile.staging`` from ``Dockerfile`` by removing the BuildKit cache mounts.

WHY: Railway requires a cache-mount id to be prefixed with the id of the service being built
(``s/<service-id>-...``). The production ``Dockerfile`` hard-codes the production service's id, so a
build in any other Railway service (a staging environment) fails. The cache mounts only speed up
repeated builds, so the staging variant simply drops them; everything else is identical.

USAGE (from apps/api)
    python scripts/make_staging_dockerfile.py            # (re)write Dockerfile.staging
    python scripts/make_staging_dockerfile.py --check    # exit 1 if Dockerfile.staging is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Dockerfile"
TARGET = ROOT / "Dockerfile.staging"

HEADER = (
    "# GENERATED by scripts/make_staging_dockerfile.py from Dockerfile: do not edit by hand.\n"
    "# Identical to Dockerfile except: the BuildKit cache mounts are removed (their ids are tied\n"
    "# to the production Railway service) and scripts/seed_staging.py is copied in.\n"
    "# Regenerate after any change to Dockerfile.\n"
)
# `RUN --mount=type=cache,...,sharing=locked \` followed by the command on the next line.
CACHE_MOUNT = re.compile(r"RUN --mount=type=cache,[^\\\n]*\\\n\s+")


def generate() -> str:
    text = SOURCE.read_text(encoding="utf-8").replace("\r\n", "\n")
    out, count = CACHE_MOUNT.subn("RUN ", text)
    if count == 0 or "--mount=type=cache" in out:
        raise SystemExit("Unexpected Dockerfile layout: cache mounts not fully removed.")
    # The production image ships no scripts/; staging also needs the seeder (run by pre-deploy).
    marker = "COPY alembic.ini ./\n"
    if out.count(marker) != 1:
        raise SystemExit("Unexpected Dockerfile layout: COPY alembic.ini line not found once.")
    out = out.replace(marker, marker + "COPY scripts/seed_staging.py ./scripts/seed_staging.py\n")
    # A `# syntax=` parser directive must stay the very first line, so the header goes after it.
    first, _, rest = out.partition("\n")
    if first.startswith("# syntax="):
        return first + "\n" + HEADER + rest
    return HEADER + out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        current = ""
        if TARGET.exists():
            current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n")
        if current != expected:
            print("Dockerfile.staging is stale; run make_staging_dockerfile.py", file=sys.stderr)
            return 1
        print("Dockerfile.staging is up to date")
        return 0
    TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
